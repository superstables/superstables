#!/usr/bin/env node
// Sets the release version everywhere it is pinned, and checks that nothing disagrees with
// package.json. package.json is the single source.
//
//   npm run version:set -- 1.2.3                  write the new version into every pin
//   npm run version:set -- 1.2.3 --title "Words"  also cut the Unreleased changelog into `## [1.2.3] - Words`
//   npm run version:set -- --check                exit 1 if a pin disagrees with package.json
//
// Three kinds of pin exist:
//   - package.json and the root entry of package-lock.json: written here;
//   - PIN_FILES, hand-written text that names the current release ("No mainnet chain is payable in
//     1.2.3", the pinned npx command in the skill): the old version is replaced by the new one;
//   - generated files (plugin manifests, the plugin's CLI reference): regenerated by
//     `npm run plugin:sync`, which this script runs. docs/cli.md and docs/cli-budget.md are in
//     PIN_FILES because they come from the CLI's help; `npm run docs:cli -- --check` confirms them.
//
// The check (test/scripts/version-pins.test.ts runs it in `npm test`) fails when
//   - a PIN_FILES file has a pin phrase naming another version, or none,
//   - package-lock.json disagrees with package.json,
//   - a tracked file other than those listed in OTHER_FILES names the current version, which means
//     a new pin was added without a place in PIN_FILES.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const PIN_FILES = [
  "budget/CLI.md",
  "budget/README.md",
  "budget/cli.mjs",
  "budget/once.mjs",
  "budget/owner-page.ts",
  "docs/buy-once.md",
  "docs/cli-budget.md",
  "docs/cli.md",
  "docs/install.md",
  "docs/security.md",
  "docs/seller-referrals.md",
  "evals/README.md",
  "skills/superstables-payments/references/discovery.md",
  "src/cli/help.ts",
];

/** Tracked files that may name the current version without being a pin in PIN_FILES, and why. */
export const OTHER_FILES = new Set([
  "package.json", // the source
  "package-lock.json", // written here
  "CHANGELOG.md", // the history; `--title` cuts the new section
  ".github/workflows/npm-stage.yml", // an example tag in an input description
  "plugin/plugin.json", // generated by plugin:sync
  "plugin/.claude-plugin/plugin.json",
  "plugin/.cursor-plugin/plugin.json",
  "plugin/skills/superstables/references/cli.md",
  "plugin/skills/superstables/references/discovery.md",
]);

// The phrases that name the current release. Each has one capture group: the version. Other
// versions in the text (a feature "added in 0.3.0", a dependency) are history, not pins.
const V = String.raw`(\d+\.\d+\.\d+)(?![\d]|\.\d)`;
const PIN_CONTEXTS = [
  new RegExp(String.raw`payable in ${V}`, "g"),
  new RegExp(String.raw`(?:Superstables client|\*\*client) ${V}`, "g"),
  new RegExp(String.raw`client version\s+${V}`, "g"),
  new RegExp(String.raw`@superstables/client@${V}`, "g"),
  new RegExp(String.raw`\b${V} release`, "g"),
  new RegExp(String.raw`For ${V},`, "g"),
  new RegExp(String.raw`skill-${V}\.zip`, "g"),
];
/** The versions that the pin phrases in `text` name. */
const pinsIn = (text) => PIN_CONTEXTS.flatMap((re) => [...text.matchAll(re)].map((m) => ({ version: m[1] })));
const STRICT = /^\d+\.\d+\.\d+$/;
const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const fix = "Run `npm run version:set -- <x.y.z>`, which rewrites every pin from package.json's version.";

const read = (root, file) => readFileSync(join(root, file), "utf8");

/** Versions that CHANGELOG.md headings name as released. */
function releasedVersions(root) {
  return new Set([...read(root, "CHANGELOG.md").matchAll(/^## \[(\d+\.\d+\.\d+)\]/gm)].map((m) => m[1]));
}

/** The problems found, each naming a file and the fix. Empty when every pin agrees. */
export function checkPins(root) {
  const version = JSON.parse(read(root, "package.json")).version;
  const problems = [];

  for (const file of PIN_FILES) {
    const found = new Set(pinsIn(read(root, file)).map((p) => p.version));
    const stale = [...found].filter((v) => v !== version);
    if (stale.length) problems.push(`${file}: names ${stale.join(", ")} but package.json is ${version}. ${fix}`);
    else if (!found.has(version)) problems.push(`${file}: does not name ${version}. If the pin moved out of this file, remove it from PIN_FILES in scripts/version-set.mjs; otherwise ${fix.toLowerCase()}`);
  }

  const lock = JSON.parse(read(root, "package-lock.json"));
  for (const [where, v] of [["version", lock.version], ['packages[""].version', lock.packages?.[""]?.version]]) {
    if (v !== version) problems.push(`package-lock.json: ${where} is ${v} but package.json is ${version}. ${fix}`);
  }

  let tracked = null;
  try {
    tracked = execFileSync("git", ["grep", "-lIE", `(^|[^0-9.])${escape(version)}([^0-9]|\\.[^0-9]|$)`], { cwd: root, encoding: "utf8" }).split("\n").filter(Boolean);
  } catch (error) {
    if (error.status !== 1) tracked = null; // not a git checkout: skip the completeness scan
    else tracked = [];
  }
  for (const file of tracked ?? []) {
    if (!PIN_FILES.includes(file) && !OTHER_FILES.has(file)) {
      problems.push(`${file}: names ${version} but is not a known pin. Add it to PIN_FILES (or OTHER_FILES, with the reason) in scripts/version-set.mjs.`);
    }
  }
  return problems;
}

/** Writes `next` into every pin. `title` cuts the Unreleased changelog into a section. */
export function setVersion(root, next, { title, plugin = true } = {}) {
  if (!STRICT.test(next)) throw new Error(`"${next}" is not a version of the form major.minor.patch`);
  const pkgText = read(root, "package.json");
  const old = JSON.parse(pkgText).version;
  if (old === next) throw new Error(`package.json is already ${next}`);
  const touched = [];
  const put = (file, text) => { writeFileSync(join(root, file), text); touched.push(file); };

  for (const file of PIN_FILES) {
    const text = read(root, file);
    if (!pinsIn(text).some((p) => p.version === old)) throw new Error(`${file} has no pin phrase naming ${old}. Fix PIN_FILES or PIN_CONTEXTS in scripts/version-set.mjs.`);
    put(file, PIN_CONTEXTS.reduce((t, re) => t.replace(re, (m, v) => (v === old ? m.replace(v, next) : m)), text));
  }
  const line = `"version": "${old}"`;
  if (!pkgText.includes(line)) throw new Error(`package.json has no ${line}`);
  put("package.json", pkgText.replace(line, `"version": "${next}"`));
  // Only the root entries: a dependency's version is never ours.
  const lockText = read(root, "package-lock.json");
  const lockRoot = new RegExp(`^(\\s{2}"version": |\\s{6}"version": )"${escape(old)}"`, "gm");
  if ((lockText.match(lockRoot) ?? []).length !== 2) throw new Error(`package-lock.json: expected the version ${old} in its two root entries`);
  put("package-lock.json", lockText.replace(lockRoot, `$1"${next}"`));

  if (title) {
    const log = read(root, "CHANGELOG.md");
    const marker = "## [Unreleased]\n\n";
    if (!log.includes(marker)) throw new Error("CHANGELOG.md has no `## [Unreleased]` heading to cut");
    put("CHANGELOG.md", log.replace(marker, `${marker}## [${next}] - ${title}\n\n`));
  }
  if (plugin) {
    execFileSync(process.execPath, [join(root, "scripts/plugin-sync.mjs")], { cwd: root, stdio: "inherit" });
  }
  return { old, touched };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL("..", import.meta.url));
  const args = process.argv.slice(2);
  if (args.includes("--check")) {
    const problems = checkPins(root);
    if (problems.length) {
      console.error(problems.join("\n"));
      process.exit(1);
    }
    console.log("Every version pin matches package.json.");
  } else {
    const next = args.find((a) => !a.startsWith("--") && a !== args[args.indexOf("--title") + 1]);
    const t = args.indexOf("--title");
    if (!next) {
      console.error("usage: npm run version:set -- <x.y.z> [--title \"Changelog title\"] | --check");
      process.exit(2);
    }
    const { old, touched } = setVersion(root, next, { title: t === -1 ? undefined : args[t + 1] });
    console.log(`Version ${old} -> ${next} in ${touched.length} files, plugin files regenerated.`);
    if (t === -1) console.log("CHANGELOG.md not touched: pass --title \"...\" to cut Unreleased into a section, or edit it by hand.");
    console.log("Next: npm run build && npm run docs:cli -- --check, then npm run plugin:check.");
  }
}
