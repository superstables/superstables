#!/usr/bin/env node
// Sets the release version everywhere it is pinned, and checks that nothing disagrees with
// package.json. package.json is the single source.
//
//   npm run version:set -- 1.2.3                  write the new version into every pin
//   npm run version:set -- 1.2.3 --title "Words"  also cut the Unreleased changelog into `## [1.2.3] - Words`
//   npm run version:set -- --check                exit 1 if a pin disagrees with package.json
//
// Three kinds of pin exist:
//   - package.json and the root entry of package-lock.json: written here;
//   - PINS, the places in hand-written text that name the current release ("No mainnet chain is
//     payable in 1.2.3"): each is a file plus an anchored pattern, so history ("the 1.0.0 release
//     added this") is never read as a pin or rewritten;
//   - generated files (plugin manifests, the plugin's CLI reference): regenerated by
//     `npm run plugin:sync`, which this script runs and `--check` runs in check mode. docs/cli.md
//     and docs/cli-budget.md are in PINS because they come from the CLI's help; `npm run docs:cli -- --check` confirms them.
//
// The check (test/scripts/version-pins.test.ts runs it in `npm test`) fails when
//   - a registered pin names another version, or a file has none,
//   - the plugin check (`plugin-sync --check`) fails,
//   - package-lock.json disagrees with package.json,
//   - CHANGELOG.md's `[Unreleased]` link does not compare from the current version, or that version has no link,
//   - a tracked file other than those listed in OTHER_FILES names the current version, which means
//     a new pin was added without a place in PINS.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const MAINNET = "No mainnet chain is payable in VER";
/** File -> anchored patterns; VER marks the version. Only these places are pins. */
export const PINS = {
  "budget/CLI.md": [MAINNET],
  "budget/README.md": ["pinned to the full VER release commit"],
  "budget/cli.mjs": [MAINNET],
  "budget/once.mjs": [MAINNET],
  "budget/owner-page.ts": [MAINNET],
  "docs/buy-once.md": [MAINNET],
  "docs/cli-budget.md": [MAINNET],
  "docs/cli.md": [MAINNET],
  "docs/install.md": [
    String.raw`describe \*\*client VER\*\*`,
    String.raw`@superstables/client@VER`,
    "commit hash of the VER release",
    String.raw`client version\s+VER`,
    "^the VER release uses",
  ],
  "docs/security.md": [
    "^Superstables client VER makes",
    MAINNET,
    "^For VER, use the agent skill zip",
    "attached to the VER release on",
    String.raw`superstables-skill-VER\.zip`,
  ],
  "docs/seller-referrals.md": [MAINNET],
  "evals/README.md": [MAINNET],
  "skill-source/references/discovery.md": [MAINNET],
  "src/cli/help.ts": [MAINNET],
};
const PIN_FILES = Object.keys(PINS);
const VER = String.raw`(\d+\.\d+\.\d+)(?!\d|\.\d)`;
const patternsFor = (file) => PINS[file].map((src) => new RegExp(src.replace("VER", VER), "gm"));
/** The versions that the registered pins in `text` name. */
const pinsIn = (file, text) => patternsFor(file).flatMap((re) => [...text.matchAll(re)].map((m) => m[1]));

/** Tracked files that may name the current version without being a pin in PINS, and why. */
export const OTHER_FILES = new Set([
  "package.json", // the source
  "package-lock.json", // written here
  "CHANGELOG.md", // the history; `--title` cuts the new section
  ".github/workflows/npm-stage.yml", // an example tag in an input description
  "plugin/plugin.json", // generated by plugin:sync, which `--check` runs in check mode
  "plugin/.claude-plugin/plugin.json",
  "plugin/.cursor-plugin/plugin.json",
  "plugin/skills/superstables/references/cli.md",
  "plugin/skills/superstables/references/discovery.md",
  "scripts/version-set.mjs", // the example version 1.2.3 in the usage comment
  "test/scripts/plugin-sync.test.ts", // fixture versions
  "test/scripts/version-pins.test.ts", // fixture versions
]);

const STRICT = /^\d+\.\d+\.\d+$/;
const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const fix = "Run `npm run version:set -- <x.y.z>`, which rewrites every pin from package.json's version.";

const read = (root, file) => readFileSync(join(root, file), "utf8");

const COMPARE = "https://github.com/superstables/superstables/compare";
const unreleasedLink = (version) => `[Unreleased]: ${COMPARE}/v${version}...HEAD`;
const versionLink = (version) => new RegExp(`^\\[${escape(version)}\\]: `, "m");

/** The problems found, each naming a file and the fix. Empty when every pin agrees. */
export function checkPins(root) {
  const version = JSON.parse(read(root, "package.json")).version;
  const problems = [];

  for (const file of PIN_FILES) {
    const found = new Set(pinsIn(file, read(root, file)));
    const stale = [...found].filter((v) => v !== version);
    if (stale.length) problems.push(`${file}: names ${stale.join(", ")} but package.json is ${version}. ${fix}`);
    else if (!found.has(version)) problems.push(`${file}: does not name ${version}. If the pin moved out of this file, fix PINS in scripts/version-set.mjs; otherwise ${fix.toLowerCase()}`);
  }

  const lock = JSON.parse(read(root, "package-lock.json"));
  for (const [where, v] of [["version", lock.version], ['packages[""].version', lock.packages?.[""]?.version]]) {
    if (v !== version) problems.push(`package-lock.json: ${where} is ${v} but package.json is ${version}. ${fix}`);
  }

  const log = read(root, "CHANGELOG.md");
  if (!log.includes(`${unreleasedLink(version)}\n`) || !versionLink(version).test(log)) {
    problems.push(`CHANGELOG.md: restore the \`[Unreleased]\` compare link from ${version} to HEAD and the ${version} compare link.`);
  }

  try {
    execFileSync(process.execPath, [join(root, "scripts/plugin-sync.mjs"), "--check"], { cwd: root, encoding: "utf8", stdio: "pipe" });
  } catch (error) {
    problems.push(`plugin files: ${String(error.stderr || error.stdout || error.message).trim()}. ${fix}`);
  }

  let tracked = [];
  try {
    tracked = execFileSync("git", ["grep", "-lIE", `(^|[^0-9.])${escape(version)}([^0-9]|\\.[^0-9]|$)`], { cwd: root, encoding: "utf8" }).split("\n").filter(Boolean);
  } catch (error) {
    if (error.status !== 1) tracked = []; // not a git checkout: skip the completeness scan
  }
  for (const file of tracked) {
    if (!PIN_FILES.includes(file) && !OTHER_FILES.has(file)) {
      problems.push(`${file}: names ${version} but is not a known pin. Add it to PINS (or OTHER_FILES, with the reason) in scripts/version-set.mjs.`);
    }
  }
  return problems;
}

/**
 * Writes `next` into every pin, whatever version each names now, so a run with the current
 * version repairs pins that fell behind. `title` cuts the Unreleased changelog into a section.
 * @param {string} root
 * @param {string} next
 * @param {{ title?: string, plugin?: boolean }} [options]
 */
export function setVersion(root, next, { title, plugin = true } = {}) {
  if (!STRICT.test(next)) throw new Error(`"${next}" is not a version of the form major.minor.patch`);
  const pkgText = read(root, "package.json");
  const old = JSON.parse(pkgText).version;
  const touched = [];
  const put = (file, text) => {
    if (text === read(root, file)) return;
    writeFileSync(join(root, file), text);
    touched.push(file);
  };

  for (const file of PIN_FILES) {
    const text = read(root, file);
    if (!pinsIn(file, text).length) throw new Error(`${file} has no pin to set. Fix PINS in scripts/version-set.mjs or the file.`);
    put(file, patternsFor(file).reduce((t, re) => t.replace(re, (m, v) => m.replace(v, next)), text));
  }
  put("package.json", pkgText.replace(/^  "version": "[^"]*"/m, `  "version": "${next}"`));
  // The root entries come first: the top-level one, then packages[""]. A dependency's version is never ours.
  const lockText = read(root, "package-lock.json");
  put("package-lock.json", lockText.replace(/^  "version": "[^"]*"/m, `  "version": "${next}"`).replace(/^      "version": "[^"]*"/m, `      "version": "${next}"`));

  if (title) {
    const log = read(root, "CHANGELOG.md");
    const marker = "## [Unreleased]\n\n";
    if (!log.includes(marker)) throw new Error("CHANGELOG.md has no `## [Unreleased]` heading to cut");
    const cut = log.replace(marker, `${marker}## [${next}] - ${title}\n\n`);
    // package.json already names `next` when an earlier run set it without --title.
    const previous = log.match(/^## \[(\d+\.\d+\.\d+)\]/m)?.[1] ?? old;
    const added = versionLink(next).test(cut) ? "" : `[${next}]: ${COMPARE}/v${previous}...v${next}\n`;
    const linked = cut.replace(/^\[Unreleased\]: .*\n/m, `${unreleasedLink(next)}\n${added}`);
    if (!linked.includes(unreleasedLink(next))) throw new Error("CHANGELOG.md has no `[Unreleased]: ` compare link to update");
    put("CHANGELOG.md", linked);
  }
  if (plugin) {
    execFileSync(process.execPath, [join(root, "scripts/plugin-sync.mjs")], { cwd: root, stdio: "inherit" });
  }
  return { old, touched };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL("..", import.meta.url));
  const args = process.argv.slice(2);
  if (args.includes("--check")) {
    const problems = checkPins(root);
    if (problems.length) {
      console.error(problems.join("\n"));
      process.exit(1);
    }
    console.log("Every version pin matches package.json.");
  } else {
    const t = args.indexOf("--title");
    const next = args.find((a, i) => STRICT.test(a) && (t === -1 || i !== t + 1));
    if (!next) {
      console.error("usage: npm run version:set -- <x.y.z> [--title \"Changelog title\"] | --check");
      process.exit(2);
    }
    const { old, touched } = setVersion(root, next, { title: t === -1 ? undefined : args[t + 1] });
    console.log(`Version ${old} -> ${next}: ${touched.length} files changed, plugin files regenerated.`);
    if (t === -1) console.log("CHANGELOG.md not touched: pass --title \"...\" to cut Unreleased into a section, or edit it by hand.");
    console.log("Next: npm run build && npm run docs:cli -- --check.");
  }
}
